use super::DrugMonograph;

pub fn find_curated(query: &str) -> Option<DrugMonograph> {
    let clean = query
        .trim()
        .to_ascii_lowercase()
        .replace(['/', '-', '+', '&'], " ");
    let words: Vec<&str> = clean.split_whitespace().collect();
    let norm = words.join(" ");

    match norm.as_str() {
        "metformin" | "metformin hydrochloride" | "glucophage" | "glycomet" => Some(metformin()),
        "atorvastatin" | "atorvastatin calcium" | "lipitor" | "storvas" | "atorva" => Some(atorvastatin()),
        "rosuvastatin" | "rosuvastatin calcium" | "crestor" | "rosuvas" | "rosave" => Some(rosuvastatin()),
        "amoxicillin" | "amoxycillin" | "amoxil" | "mox" | "novamox" => Some(amoxicillin()),
        "amoxicillin clavulanate" | "amoxicillin clavulanic acid" | "amoxicillin and clavulanate"
        | "amoxicillin and clavulanic acid" | "amoxyclav" | "augmentin" | "moxikind cv" | "clavam" => {
            Some(amoxicillin_clavulanate())
        }
        "paracetamol" | "acetaminophen" | "tylenol" | "calpol" | "dolo" | "crocin" | "pcm" => {
            Some(paracetamol())
        }
        "ibuprofen" | "advil" | "motrin" | "brufen" => Some(ibuprofen()),
        "omeprazole" | "prilosec" | "omez" | "omizac" => Some(omeprazole()),
        "pantoprazole" | "protonix" | "pan" | "pantocid" | "pantop" => Some(pantoprazole()),
        _ => None,
    }
}

